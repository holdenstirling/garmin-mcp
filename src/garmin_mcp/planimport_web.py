"""HTTP routes for plan imports (``planimport``), for a linked coach with ``can_edit_plan``
(``/app/api/coach/athletes/{athlete_id}/plan/import...``) and for the athlete themself
(``/app/api/plan/import...``). Built by ``webapp.build_app_routes`` from its own helpers so
the same guards apply: ``plan_api`` (session, Host, Origin + JSON on mutating calls, coach
accounts limited to coach paths) and, for the raw-body file upload, the same checks as chat
attachments.

    GET  .../plan/import               status: undo available?, last import, file reads left
    GET  .../plan/import/draft         current plan as grid rows + week templates
    GET  .../plan/import/template.csv  the CSV template
    GET  .../plan/import/export.csv    the current plan as CSV (template columns)
    GET  .../plan/import/export.ics    the current plan as an iCal file
    GET  .../plan/import/pending       the actor's newest draft preview (24 h), or null
    GET  .../plan/import/templates     plan templates (generated by the builder)
    POST .../plan/import/template/{id} {start?, weeks?, mode?} -> preview
    POST .../plan/import/rows          {rows, name?, source?, mode?} -> preview
    POST .../plan/import/file?name=&start=&via=&mode=&map=&ai=&size=&sheet=   raw file(s) -> preview
                                       (or {"mapping": ...} when a sheet's columns need picking)
    POST .../plan/import/link          {url, start?, mode?} a Google Sheets/Docs link -> preview
    POST .../plan/import/{id}/update   {rows, mode?, issues?, name?, schedule?} -> preview (same draft)
    POST .../plan/import/mine          coach only: {name, import_id? | from: "plan"} save as my template
    POST .../plan/import/mine/{tid}/delete   coach only
    POST .../plan/import/{id}/discard  drop the draft
    POST .../plan/import/{id}/apply    install the previewed plan (athlete notified)
    POST .../plan/import/undo          put the previous plan back (7 days)

Several files go in one request (``size`` repeated, one per file, with ``name`` repeated):
sheets, calendars and workout files are parsed here and photos/PDFs/text are read by the
model together in one call.
"""

from __future__ import annotations

import json
import logging
import re
from collections.abc import Awaitable, Callable
from datetime import date, datetime, timedelta
from typing import Any

import anyio
from starlette.requests import Request
from starlette.responses import JSONResponse, Response
from starlette.routing import Route

from . import planlinks
from .attachments import MAX_UPLOAD
from .logs import log_event
from .planbuilder import PlanError
from .planformats import (
    MERGE_MODES,
    TEMPLATE_GROUPS,
    TEMPLATE_LEVELS,
    FormatError,
    export_csv,
    export_ics,
    template_catalog,
    template_rows,
    week_day_from_name,
    workout_row,
)
from .planimport import (
    AI_PER_DAY,
    INTENSITIES,
    SPORTS,
    ImportService,
    PlanImportError,
    csv_template,
    detect,
    extract,
    next_monday,
    plan_rows,
    week_templates,
)

logger = logging.getLogger(__name__)
MAX_ROWS_BODY = 512 * 1024
SOURCE_LABEL = {"csv": "CSV", "xlsx": "Excel", "ods": "spreadsheet", "ics": "calendar file", "pdf": "PDF",
                "image": "photo", "text": "text", "zwo": "Zwift workout", "erg": "ERG/MRC workout",
                "docx": "Word document", "odt": "document"}
_URL_ONLY = re.compile(rb"\s*https?://\S+\s*")
MAX_PARTS = 10


def make_routes(*, importer: ImportService, plans: Any, coach: Any, links: Any, auth: Any,
                settings: Any, host_ok: Callable[[Request], bool],
                plan_api: Callable[..., Callable[[Request], Awaitable[Response]]],
                plan_call: Callable[[Callable[[], Any]], Awaitable[Any]],
                user_error: type[Exception], public_plan: Callable[..., Any],
                notify: Callable[..., None], coach_chat: Any,
                structured: Callable[..., Awaitable[dict[str, Any]]] | None,
                now: Callable[[str], datetime]) -> list[Route]:

    def err(status: int, message: str) -> JSONResponse:
        return JSONResponse({"error": message}, status_code=status)

    def who(request: Request, user_id: str, *, edit: bool = True) -> tuple[str, str, dict[str, Any] | None]:
        """(athlete id, role, coach link). Coach routes check the link (and edit access)."""
        aid = request.path_params.get("athlete_id")
        if aid is None:
            return user_id, "athlete", None
        link = links.require(user_id, str(aid), perm="can_edit_plan" if edit else None)
        return str(aid), "coach", link

    def actor_name(user_id: str, link: dict[str, Any] | None) -> str:
        name = (auth.profile(user_id).get("name") or "").strip()
        if name:
            return name
        return link["email"].split("@")[0] if link else "You"

    def race_of(aid: str, today: date) -> str | None:
        g = coach.active_goal(aid)
        d = (g or {}).get("date")
        return d if isinstance(d, str) and d > today.isoformat() else None

    async def status(request: Request, user_id: str) -> Response:
        def run() -> dict[str, Any]:
            aid, role, link = who(request, user_id, edit=False)
            today = plans.today(aid)
            return importer.status(aid) | {
                "can_edit": role == "athlete" or bool((link or {}).get("can_edit_plan")),
                "can_save_templates": role == "coach",
                "race_date": race_of(aid, today),
                "ai_left": importer.ai_left(user_id, today) if structured else 0,
                "ai_per_day": AI_PER_DAY if structured else 0,
                "next_monday": next_monday(today).isoformat(), "today": today.isoformat()}
        return JSONResponse(await plan_call(run))

    async def draft(request: Request, user_id: str) -> Response:
        def run() -> dict[str, Any]:
            aid, _, _ = who(request, user_id)
            today = plans.today(aid)
            return {"rows": plan_rows(plans.get(aid), today),
                    "templates": week_templates(coach.athlete(aid), coach.active_goal(aid)),
                    "sports": [s for s in SPORTS if s != "rest"], "intensities": list(INTENSITIES),
                    "next_monday": next_monday(today).isoformat(), "today": today.isoformat()}
        return JSONResponse(await plan_call(run))

    async def template(request: Request, user_id: str) -> Response:
        aid, _, _ = await plan_call(lambda: who(request, user_id, edit=False))
        return Response(csv_template(plans.today(aid)), media_type="text/csv",
                        headers={"Content-Disposition": 'attachment; filename="rabbit-plan-template.csv"'})

    def mode_of(v: Any) -> str:
        if v in (None, ""):
            return "replace"
        if v not in MERGE_MODES:
            raise user_error("mode must be replace, add or weeks")
        return str(v)

    async def read_body(request: Request) -> dict[str, Any]:
        raw = await request.body()
        if len(raw) > MAX_ROWS_BODY * 2:
            raise user_error("That plan is too large to send at once.", 413)
        body = json.loads(raw or b"null")
        if not isinstance(body, dict):
            raise ValueError("body")
        return body

    async def pending(request: Request, user_id: str) -> Response:
        def run() -> dict[str, Any] | None:
            aid, _, _ = who(request, user_id)
            return importer.latest(aid, user_id)
        return JSONResponse({"preview": await plan_call(run)})

    async def update(request: Request, user_id: str) -> Response:
        iid = request.path_params["import_id"]
        body = await read_body(request)
        if not isinstance(body.get("rows"), list):
            raise ValueError("body")
        mode = mode_of(body.get("mode")) if body.get("mode") is not None else None
        issues = body.get("issues") if isinstance(body.get("issues"), list) else None
        schedule = body.get("schedule") if isinstance(body.get("schedule"), dict) else None

        def run() -> dict[str, Any]:
            aid, _, _ = who(request, user_id)
            return importer.update(aid, iid, body["rows"], actor=user_id, mode=mode, issues=issues,
                                   name=body.get("name") if isinstance(body.get("name"), str) else None,
                                   schedule=schedule)
        return JSONResponse({"preview": await plan_call(run)})

    async def discard(request: Request, user_id: str) -> Response:
        iid = request.path_params["import_id"]

        def run() -> None:
            aid, _, _ = who(request, user_id)
            importer.discard(aid, iid, actor=user_id)
        await plan_call(run)
        return JSONResponse({"ok": True})

    async def templates(request: Request, user_id: str) -> Response:
        def run() -> dict[str, Any]:
            aid, role, _ = who(request, user_id)
            goal = coach.active_goal(aid)
            return {"templates": template_catalog(),
                    "groups": [{"id": g, "label": label} for g, label in TEMPLATE_GROUPS],
                    "levels": list(TEMPLATE_LEVELS), "race_date": race_of(aid, plans.today(aid)),
                    "race_title": (goal or {}).get("title"),
                    "mine": importer.my_templates(user_id) if role == "coach" else None}
        return JSONResponse(await plan_call(run))

    async def template_preview(request: Request, user_id: str) -> Response:
        tid = request.path_params["template_id"]
        body = await read_body(request)
        weeks = body.get("weeks") if isinstance(body.get("weeks"), int) else None
        mode = mode_of(body.get("mode")) if body.get("mode") is not None else None
        level = body.get("level") if isinstance(body.get("level"), str) else None
        on_race = body.get("end") == "race"

        def run() -> dict[str, Any]:
            aid, role, _ = who(request, user_id)
            today = plans.today(aid)
            start = next_monday(today)
            if isinstance(body.get("start"), str):
                try:
                    start = date.fromisoformat(body["start"])
                except ValueError:
                    raise user_error("start must be YYYY-MM-DD") from None
            if tid.startswith("my"):
                if role != "coach":
                    raise user_error("Not found", 404)
                got, name = importer.my_template_rows(user_id, tid, start)
                return importer.preview(aid, got, actor=user_id, source="My template", name=name,
                                        mode=mode or "replace", start=start)
            athlete, goal = coach.athlete(aid), coach.active_goal(aid)
            end = None
            if on_race:
                r = race_of(aid, today)
                if r is None:
                    raise user_error("There's no upcoming race date to end on.")
                end = date.fromisoformat(r)
            try:
                got, name = template_rows(tid, athlete, goal, today=today, start=start, weeks=weeks,
                                          week_templates=week_templates, level=level, end=end)
            except FormatError as e:
                raise PlanImportError(str(e)) from None
            if level:
                name = f"{name} ({level})"
            sug = "add" if tid == "strength" else "replace"
            return importer.preview(aid, got, actor=user_id, source="Template", name=name,
                                    mode=mode or (sug if plans.get(aid) is not None else "replace"),
                                    suggested_mode=sug)
        return JSONResponse({"preview": await plan_call(run)})

    async def export(request: Request, user_id: str) -> Response:
        fmt = request.path_params["fmt"]
        if fmt not in ("csv", "ics"):
            raise user_error("Not found", 404)

        def run() -> tuple[Any, Any]:
            aid, _, _ = who(request, user_id, edit=False)
            return plans.get(aid), coach.active_goal(aid)
        plan, goal = await plan_call(run)
        if plan is None:
            raise user_error("There's no plan to download yet.", 404)
        name = ((goal or {}).get("title") or "Training plan")[:60]
        slug = "".join(c if c.isalnum() else "-" for c in name.lower()).strip("-")[:40] or "plan"
        if fmt == "csv":
            body, media = export_csv(plan, tuple(INTENSITIES)), "text/csv; charset=utf-8"
        else:
            body, media = export_ics(plan, name=name), "text/calendar; charset=utf-8"
        return Response(body, media_type=media, headers={
            "Content-Disposition": f'attachment; filename="rabbit-{slug}.{fmt}"', "Cache-Control": "no-store"})

    async def rows(request: Request, user_id: str) -> Response:
        raw = await request.body()
        if len(raw) > MAX_ROWS_BODY:
            raise user_error("That plan is too large to send at once.", 413)
        body = json.loads(raw or b"null")
        if not isinstance(body, dict) or not isinstance(body.get("rows"), list):
            raise ValueError("body")

        mode = mode_of(body.get("mode"))

        def run() -> dict[str, Any]:
            aid, _, _ = who(request, user_id)
            src = body.get("source") if body.get("source") in ("grid", "template") else "grid"
            return importer.preview(aid, body["rows"], actor=user_id, source="Rabbit" if src == "grid" else "template",
                                    name=body.get("name") if isinstance(body.get("name"), str) else None, mode=mode)
        return JSONResponse({"preview": await plan_call(run)})

    def split_parts(request: Request, data: bytes) -> list[tuple[str, bytes]]:
        """(name, bytes) per file: one file, or several with ``size``/``name`` repeated."""
        names = [n[:120] for n in request.query_params.getlist("name")] or ["plan"]
        sizes = request.query_params.getlist("size")
        if not sizes:
            return [(names[0], data)]
        try:
            ns = [int(x) for x in sizes]
        except ValueError:
            raise user_error("bad size") from None
        if not 1 <= len(ns) <= MAX_PARTS or any(n <= 0 for n in ns) or sum(ns) != len(data):
            raise user_error(f"Send up to {MAX_PARTS} files at a time.")
        out, at = [], 0
        for i, n in enumerate(ns):
            out.append((names[i] if i < len(names) else f"file {i + 1}", data[at:at + n]))
            at += n
        return out

    async def file_preview(request: Request, user_id: str, data: bytes) -> dict[str, Any]:
        return await preview_parts(request, user_id, split_parts(request, data))

    async def fetch_link(url: str) -> tuple[str, bytes]:
        try:
            _kind, body, name = await planlinks.fetch_google(url)
        except PlanError as e:
            raise user_error(str(e)) from None
        except Exception as e:  # network trouble
            log_event(logger, logging.WARNING, "plan_import_link_failed", error=type(e).__name__)
            raise user_error("Couldn't reach Google just now. Try again in a minute.", 502) from None
        return name, body

    async def preview_parts(request: Request, user_id: str, parts: list[tuple[str, bytes]],
                            body: dict[str, Any] | None = None) -> dict[str, Any]:
        """Files (or a fetched link) -> preview, or {"mapping": ...}. Options come from the
        query string (file upload) or ``body`` (link)."""
        aid, _, _ = await plan_call(lambda: who(request, user_id))
        q: Any = dict(request.query_params) if body is None else {k: v for k, v in body.items() if isinstance(v, str)}
        via_tp = q.get("via") == "trainingpeaks"
        force_ai = q.get("ai") == "1"
        mode = mode_of(q.get("mode"))
        mapping = None
        if q.get("map"):
            try:
                mapping = json.loads(q["map"])
            except ValueError:
                raise user_error("bad mapping") from None
        sheet = None
        if q.get("sheet") not in (None, ""):
            try:
                sheet = int(q["sheet"])
            except ValueError:
                raise user_error("bad sheet") from None
        s = q.get("start")
        if s:
            try:
                start = date.fromisoformat(s)
            except ValueError:
                raise user_error("start must be YYYY-MM-DD") from None
        else:
            start = next_monday(plans.today(aid))
        today = plans.today(aid)
        day = None
        if q.get("day"):
            try:
                day = date.fromisoformat(q["day"])
            except ValueError:
                raise user_error("day must be YYYY-MM-DD") from None
        # A pasted link on its own: Google Sheets/Docs are fetched (allowlisted), anything
        # else gets a "download it" message from detect().
        linked = False
        if len(parts) == 1 and len(parts[0][1]) < 2100 and _URL_ONLY.fullmatch(parts[0][1]) \
                and planlinks.google_export_url(parts[0][1].decode("utf-8", "replace").strip()):
            parts = [await fetch_link(parts[0][1].decode("utf-8", "replace").strip())]
            linked = True
        ftp = coach.athlete(aid).get("ftp_w")
        tz = now(aid).tzinfo
        got: list[dict[str, Any]] = []
        warns: list[str] = []
        kinds: list[str] = []
        ai_parts: list[tuple[str, bytes, str]] = []
        workouts: list[tuple[str, dict[str, Any]]] = []
        meta: dict[str, Any] = {}
        for name, blob in parts:
            kind = await plan_call(lambda b=blob, n=name: detect(b, n))
            kinds.append(kind)
            parsed = None if force_ai and kind in ("csv", "xlsx", "ods") else await plan_call(
                lambda k=kind, b=blob, n=name: importer.rows_from_file(
                    k, b, tz=tz, mapping=mapping, ftp=ftp, name=n, sheet=sheet if len(parts) == 1 else None, meta=meta))
            if isinstance(parsed, dict) and "mapping" in parsed:
                if len(parts) > 1:
                    raise user_error(f"Couldn't find the columns in {name}. Drop it on its own to pick them.")
                return {"mapping": parsed["mapping"] | {"name": name, "sheets": meta.get("sheets") or [],
                                                        "sheet": meta.get("sheet")}}
            if isinstance(parsed, dict) and "text" in parsed:
                ai_parts.append(("text", parsed["text"], name))
            elif isinstance(parsed, dict) and "workout" in parsed:
                workouts.append((name, parsed["workout"]))
                warns += parsed["warnings"]
            elif parsed is None:
                if kind in ("csv", "xlsx", "ods"):
                    kind = "text"
                ai_parts.append((kind, blob, name))
            else:
                rows, w = parsed
                got += rows
                warns += w
        # Workout files: on the day the file name says ("Week 2 Day 3", "W2D3"), else on
        # ``day`` (default tomorrow) and the days after it, one per file.
        nxt = day or (today + timedelta(days=1))
        for i, (name, w) in enumerate(workouts):
            wd = week_day_from_name(name)
            if wd and 1 <= wd[0] <= 60:
                got.append(workout_row(w, line=i + 1, name=name, week=wd[0], weekday=wd[1]))
            else:
                got.append(workout_row(w, line=i + 1, name=name, when=nxt))
                nxt += timedelta(days=1)
        label = ("TrainingPeaks " if via_tp else "") + (
            SOURCE_LABEL.get(kinds[0], kinds[0]) if len(set(kinds)) == 1 else "files")
        if linked:
            label = "Google Sheets" if parts[0][0].endswith(".csv") else "Google Docs"
        pname = parts[0][0].rsplit(".", 1)[0][:80] if len(parts) == 1 else None
        if pname and (linked or pname.lower() in ("pasted", "plan", "image", "clipboard")):
            pname = None
        if ai_parts:
            if structured is None:
                raise user_error("Reading PDFs and photos isn't available on this server. "
                                 "Use the CSV template instead.")
            await plan_call(lambda: importer.take_ai(user_id, today))
            try:
                rows, w2, mname = await extract(structured, ai_parts, today=today, start=start)
            except PlanError as e:
                raise user_error(str(e)) from None
            except Exception as e:  # model down, rate limited, refused
                log_event(logger, logging.WARNING, "plan_import_model_failed", error=type(e).__name__)
                raise user_error("Rabbit couldn't read that file just now. Try again in a minute, "
                                 "or use the CSV template.", 502) from None
            got += rows
            label += " (read by Rabbit)"
            pname = mname or pname
            warns = ["Rabbit read this file: check the sessions before you apply."] + w2 + warns
        if not got:
            raise user_error("No sessions found in that file.")
        workout_only = bool(workouts) and not ai_parts and len(got) == len(workouts)
        has_plan = await plan_call(lambda: plans.get(aid) is not None)
        if workout_only and q.get("mode") in (None, "") and has_plan:
            mode = "add"
        return await plan_call(lambda: importer.preview(
            aid, got, actor=user_id, source=label, name=pname, start=start, warnings=warns, mode=mode,
            suggested_mode="add" if workout_only else None, sheets=meta.get("sheets"), sheet=meta.get("sheet")))

    async def link(request: Request, user_id: str) -> Response:
        body = await read_body(request)
        url = body.get("url")
        if not isinstance(url, str) or not url.strip():
            raise ValueError("body")
        await plan_call(lambda: who(request, user_id))
        if planlinks.google_export_url(url.strip()) is None:
            raise user_error("Rabbit only opens Google Sheets and Docs links. Download the file and drop it "
                             "here, or paste the plan's text.")
        try:
            pv = await preview_parts(request, user_id, [(("link"), url.strip().encode())], body=body)
        except PlanImportError as e:
            raise user_error(str(e)) from None
        return JSONResponse(pv if "mapping" in pv else {"preview": pv})

    async def save_mine(request: Request, user_id: str) -> Response:
        body = await read_body(request)
        name = body.get("name")
        if not isinstance(name, str):
            raise ValueError("body")

        def run() -> dict[str, Any]:
            aid, role, _ = who(request, user_id)
            if role != "coach":
                raise user_error("Only coaches can save templates.", 403)
            if isinstance(body.get("import_id"), str):
                rows, _ = importer.draft_rows(aid, body["import_id"], user_id)
            elif body.get("from") == "plan":
                rows = plan_rows(plans.get(aid), plans.today(aid))
            else:
                raise ValueError("body")
            return importer.save_template(user_id, name, rows)
        t = await plan_call(run)
        log_event(logger, logging.INFO, "plan_template_saved", weeks=t["weeks"], sessions=t["sessions"])
        return JSONResponse({"template": t, "mine": await plan_call(lambda: importer.my_templates(user_id))})

    async def delete_mine(request: Request, user_id: str) -> Response:
        tid = request.path_params["template_id"]

        def run() -> list[dict[str, Any]]:
            _, role, _ = who(request, user_id)
            if role != "coach":
                raise user_error("Only coaches can save templates.", 403)
            importer.delete_template(user_id, tid)
            return importer.my_templates(user_id)
        return JSONResponse({"mine": await plan_call(run)})

    async def apply(request: Request, user_id: str) -> Response:
        iid = request.path_params["import_id"]

        def run() -> tuple[dict[str, Any], dict[str, Any], str, str, dict[str, Any] | None]:
            aid, role, link = who(request, user_id)
            name = actor_name(user_id, link)
            plan, summary = importer.apply(aid, iid, actor=user_id, actor_name=name, actor_role=role)
            return plan, summary, aid, role, link
        plan, summary, aid, role, link = await plan_call(run)
        if role == "coach" and link is not None:
            first = summary["by_name"].split(" ")[0]
            starts = date.fromisoformat(summary["first_day"])
            text = (f"{first} loaded your plan: {summary['weeks']} week{'s' if summary['weeks'] != 1 else ''}, "
                    f"starts {starts:%a %b %-d}. Open Plan to see what changed.")
            try:
                t = coach_chat.open_thread(aid, link["email"])
                coach_chat.post(aid, t["id"], sender="coach", text=text, coach=link["email"])
            except Exception as e:  # the plan is in; the message is best effort
                log_event(logger, logging.WARNING, "plan_import_message_failed", error=type(e).__name__)
            notify(aid, summary["by_name"] or "Your coach", text)
        log_event(logger, logging.INFO, "plan_imported", user_id=aid, role=role, weeks=summary["weeks"],
                  sessions=summary["sessions"], source=summary["source"])
        return JSONResponse({"plan": public_plan(plan, plans.today(aid)), "summary": summary})

    async def undo(request: Request, user_id: str) -> Response:
        def run() -> tuple[Any, str, str, dict[str, Any] | None]:
            aid, role, link = who(request, user_id)
            # The athlete may always undo a coach's import of their own plan.
            restored = importer.undo(aid, actor=user_id, may_undo_others=role == "athlete")
            return restored, aid, role, link
        restored, aid, role, link = await plan_call(run)
        if role == "coach" and link is not None:
            name = actor_name(user_id, link).split(" ")[0]
            text = f"{name} undid the plan they loaded; your previous plan is back."
            try:
                t = coach_chat.open_thread(aid, link["email"])
                coach_chat.post(aid, t["id"], sender="coach", text=text, coach=link["email"])
            except Exception as e:
                log_event(logger, logging.WARNING, "plan_import_message_failed", error=type(e).__name__)
            notify(aid, name or "Your coach", text)
        return JSONResponse({"plan": public_plan(plans.get(aid), plans.today(aid)), "restored": restored is not None})

    async def upload(request: Request) -> Response:
        """Raw-body file upload. Same guards as _api, minus the JSON content type."""
        if not host_ok(request):
            return err(400, "bad host")
        user_id = auth.user_for(request)
        if user_id is None:
            return err(401, "not signed in")
        if request.headers.get("origin", "") != settings.public_base_url:
            return err(403, "bad origin")
        if user_id.startswith("coach_") and "athlete_id" not in request.path_params:
            return err(403, "Coach accounts can only use the coach view.")
        try:
            declared = int(request.headers.get("content-length") or 0)
        except ValueError:
            return err(400, "bad request")
        if declared > MAX_UPLOAD:
            return err(413, "That file is too large (max 10 MB).")
        buf = bytearray()
        async for chunk in request.stream():
            buf += chunk
            if len(buf) > MAX_UPLOAD:
                return err(413, "That file is too large (max 10 MB).")
        try:
            pv = await file_preview(request, user_id, bytes(buf))
            if "mapping" in pv:
                return JSONResponse(pv, headers={"Cache-Control": "no-store"})
        except user_error as e:  # type: ignore[misc]
            return err(getattr(e, "status", 400), getattr(e, "message", str(e)))
        except PlanImportError as e:
            return err(400, str(e))
        except Exception as e:
            log_event(logger, logging.ERROR, "app_unexpected_error", path=request.url.path,
                      error=type(e).__name__)
            return err(500, f"Internal error ({type(e).__name__})")
        resp = JSONResponse({"preview": pv}, status_code=201)
        resp.headers["Cache-Control"] = "no-store"
        return resp

    out: list[Route] = []
