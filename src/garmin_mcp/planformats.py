    # strength add-on
    days = [d for d in (athlete.get("available_days") or []) if d in WEEKDAYS] or ["tue", "thu", "sat"]
    long_day = athlete.get("long_day") if athlete.get("long_day") in WEEKDAYS else "sat"
    pool = [d for d in WEEKDAYS if d != long_day]
    pref = [d for d in pool if d in days] or pool
    s1 = pref[0]
    s2 = next((d for d in pref if WEEKDAYS.index(d) - WEEKDAYS.index(s1) >= 2), pool[3])
    mob = next((d for d in reversed(pool) if d not in (s1, s2)), "sun")
    for wi in range(n):
        light = (wi + 1) % 4 == 0
        for d, title, mins, it in ((s1, "Strength & mobility", 30 if light else 40, "strength"),
                                   (s2, "Strength & mobility", 30, "strength"),
                                   (mob, "Mobility", 20, "mobility")):
            if light and d == s2:
                continue
            day = start + timedelta(weeks=wi, days=WEEKDAYS.index(d))
            rows.append({"date": day.isoformat(), "sport": "strength", "title": title, "minutes": mins,
                         "intensity": it, "notes": ""})
    return rows, label


