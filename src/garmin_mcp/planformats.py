                rows.append({"date": d.isoformat(), "sport": r["sport"], "title": r["title"],
                             "minutes": r["minutes"], "intensity": r["intensity"] if kind != "build" or r["intensity"] != "threshold" else "tempo",
                             "notes": ""})
