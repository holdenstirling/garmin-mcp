"""More ways in (and out) for plan imports, all pure and deterministic:

* free-text durations and distances inside a cell ("45' easy", "1h15 long ride", "10k tempo");
* week-grid sheets (rows = weeks, columns = Mon..Sun, cells = "45' easy run");
* sheets whose headers we don't know: ``mapping_info`` guesses a column for each field so the
  app can show a column-mapping step with the dropdowns prefilled;
* structured workout files: Zwift ``.zwo`` (XML) and ``.erg`` / ``.mrc`` (text), turned into
  the builder's steps (zones from %FTP, the exact % kept on the step as ``pct``);
* merge modes (replace / add to the current plan / replace only the imported weeks) and
  date shifting;
* plan templates generated by ``planbuilder`` for the athlete's hours, level and days;
* export of the current plan as CSV (the template's columns) and as an iCal file.

``planimport`` wires these into its pipeline; nothing here touches storage or the model.
"""

